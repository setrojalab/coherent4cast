script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value=TRUE)[1])
base <- normalizePath(file.path(dirname(script), ".."), winslash="/")
if(nzchar(Sys.getenv("COHERENTSURV_LIBRARY"))) .libPaths(c(Sys.getenv("COHERENTSURV_LIBRARY"),.libPaths()))
source(file.path(base,"replication/research_metrics.R"))
library(coherentSurv)
checks <- list()
check <- function(name,ok) {checks[[length(checks)+1L]] <<- data.frame(check=name,pass=isTRUE(ok)); if(!isTRUE(ok))stop(name)}
same <- function(a,b,tol=1e-12)isTRUE(all.equal(as.numeric(a),as.numeric(b),tolerance=tol))
rejects <- function(expr)inherits(tryCatch(force(expr),error=function(e)e),"error")
p <- c(.9,.7,.4,.1); tt <- c(.5,2,.5,2); ss <- c(1,0,1,0)
a <- cs_research_report(p,tt,ss,1,thresholds=c(.2,.5,.8),false_positive_cost=2,
  false_negative_cost=10,loss_unit="illustrative loss units")
getmetric <- function(a,nm)a$metrics$estimate[match(nm,a$metrics$metric)]
check("Hand calculation: Brier",same(getmetric(a,"Brier"),.2175))
check("Hand calculation: AUROC",same(getmetric(a,"AUROC"),.75))
check("Hand calculation: AP",same(getmetric(a,"average_precision_IPCW"),5/6))
mid <- a$thresholds[2,]
check("Hand calculation: confusion cells",same(mid[c("TP","FN","FP","TN")],rep(1,4)))
check("Hand calculation: sensitivity specificity PPV NPV",same(mid[c("sensitivity","specificity","PPV","NPV")],rep(.5,4)))
check("Hand calculation: FNR FPR",same(mid[c("false_negative_rate","false_positive_rate")],c(.5,.5)))
check("Hand calculation: alert fraction",same(mid$alert_fraction,.5))
check("Hand calculation: net benefit",same(mid$net_benefit,0))
check("Hand calculation: action-all and action-none",same(mid[c("net_benefit_all","net_benefit_none")],c(0,0)))
check("Hand calculation: fixed loss",same(mid$fixed_loss,3))
g <- list(case=c(.5,1,1,1),horizon=c(1,.5,1,1))
b <- cs_research_report(p,tt,ss,1,censor_survival=g,thresholds=.5)
check("Weighted Brier oracle",same(getmetric(b,"Brier"),1.37/4))
check("Weighted AUROC oracle",same(getmetric(b,"AUROC"),7/9))
check("Weighted AP oracle",same(getmetric(b,"average_precision_IPCW"),13/15))
check("Weighted confusion oracle",same(b$thresholds[c("TP","FN","FP","TN")],c(2,1,2,1)))
ties <- cs_research_report(rep(.5,4),tt,ss,1,thresholds=.5)
check("Tied score AP equals weighted event fraction",same(getmetric(ties,"average_precision_IPCW"),.5))
check("Tied score AUROC half credit",same(getmetric(ties,"AUROC"),.5))
near <- cs_research_report(c(.5+2*.Machine$double.eps,.5),c(.5,2),c(1,0),1)
check("AP distinguishes representable near-ties",same(getmetric(near,"average_precision_IPCW"),1))
zero <- cs_research_report(p,rep(2,4),rep(0,4),1)
check("No-event AP undefined",is.na(getmetric(zero,"average_precision_IPCW")))
check("No-event sensitivity undefined",is.na(getmetric(zero,"sensitivity")))
check("No usable validation outcomes rejected",rejects(cs_research_report(c(.2,.3),c(.2,.4),c(0,0),1)))
check("Zero censoring positivity rejected",rejects(cs_research_report(p,tt,ss,1,censor_survival=list(case=rep(0,4),horizon=rep(1,4)))))
check("Invalid probability rejected",rejects(cs_research_report(c(2,p[-1]),tt,ss,1)))
check("Invalid threshold rejected",rejects(cs_research_report(p,tt,ss,1,thresholds=1)))
check("Partial cost declaration rejected",rejects(cs_research_report(p,tt,ss,1,false_positive_cost=2)))
check("Missing cost units rejected",rejects(cs_research_report(p,tt,ss,1,false_positive_cost=2,false_negative_cost=10)))
check("Fixed-loss overflow rejected",rejects(cs_research_report(p,tt,ss,1,thresholds=.5,
  censor_survival=list(case=rep(.1,4),horizon=rep(.1,4)),false_positive_cost=1e308,
  false_negative_cost=1e308,loss_unit="units")))
large <- cs_research_report(p,tt,ss,1,thresholds=.5,false_positive_cost=1e308,
  false_negative_cost=1e308,loss_unit="units")
check("Representable fixed loss avoids intermediate overflow",same(large$thresholds$fixed_loss/1e307,5))
set.seed(27); before <- .Random.seed
boot <- cs_research_report(p,tt,ss,1,bootstrap_reps=100,seed=82)
check("Caller random stream preserved",identical(before,.Random.seed))
check("All bootstrap draws retained",nrow(boot$bootstrap_draws)==100)
j <- match("average_precision_IPCW",boot$bootstrap$metric)
check("Undefined bootstrap draws counted",boot$bootstrap$finite_replicates[j]<100)
check("Undefined bootstrap interval withheld",is.na(boot$bootstrap$lower[j]) && is.na(boot$bootstrap$upper[j]))
check("Per-metric bootstrap status matches finite draw counts",all(boot$bootstrap$status ==
  ifelse(boot$bootstrap$finite_replicates==100,"percentile_approximation","undefined_draws_interval_withheld")))
check("No false exact bootstrap assertion",grepl("Not simultaneous, finite-sample exact",boot$uncertainty,fixed=TRUE))
boot2 <- cs_research_report(p,tt,ss,1,bootstrap_reps=100,seed=82)
check("Seeded reproducibility",identical(boot$bootstrap_draws,boot2$bootstrap_draws))
forecast <- data.frame(unit=c(1,1,2,2),landmark=0,horizon=1,
  target=rep(c("burden_a","burden_b"),2),estimate=c(2,.2,1,.5),time_unit="year")
cost <- cs_value_burden(forecast,c(burden_a=100,burden_b=1000),"USD 2026")
check("Linearity expected-cost oracle",same(cost$total$expected_cost,c(400,600)))
check("Cost component summation",same(cost$components$expected_cost,c(200,200,100,500)))
check("Missing burden component rejected before total",rejects(cs_value_burden(forecast[-4,],c(burden_a=100,burden_b=1000),"USD 2026")))
multiple_horizons <- rbind(forecast,transform(forecast,horizon=2))
check("Complete horizons remain separate",same(cs_value_burden(multiple_horizons,c(burden_a=100,burden_b=1000),"USD 2026")$total$expected_cost,c(400,600,400,600)))
check("Missing component at a second horizon rejected",rejects(cs_value_burden(multiple_horizons[-8,],c(burden_a=100,burden_b=1000),"USD 2026")))
factor_targets <- forecast; factor_targets$target <- factor(factor_targets$target)
check("Factor targets match costs by name",same(cs_value_burden(factor_targets,c(burden_b=1000,burden_a=100),"USD 2026")$total$expected_cost,c(400,600)))
mixed_units <- forecast; mixed_units$time_unit[2] <- "month"
check("Inconsistent component time units rejected",rejects(cs_value_burden(mixed_units,c(burden_a=100,burden_b=1000),"USD 2026")))
check("Duplicate event cost row rejected",rejects(cs_value_burden(rbind(forecast,forecast[1,]),c(burden_a=100,burden_b=1000),"USD 2026")))
check("Duplicate cost target names rejected",rejects(cs_value_burden(forecast,c(burden_a=100,burden_a=1000),"USD 2026")))
unknown_target <- forecast; unknown_target$target[4] <- "burden_unknown"
check("Unknown burden target rejected",rejects(cs_value_burden(unknown_target,c(burden_a=100,burden_b=1000),"USD 2026")))
check("Absent target cost rejected",rejects(cs_value_burden(forecast,c(burden_a=100,burden_b=1000,burden_unknown=2),"USD 2026")))
check("Unmatched costs rejected",rejects(cs_value_burden(forecast,c(burden_a=100),"USD 2026")))
check("Negative costs rejected",rejects(cs_value_burden(forecast,c(burden_a=-1,burden_b=1000),"USD 2026")))
check("Undefined cost units rejected",rejects(cs_value_burden(forecast,c(burden_a=100,burden_b=1000),"")))
overflow <- forecast; overflow$estimate <- 1e200
check("Cost-product overflow rejected",rejects(cs_value_burden(overflow,c(burden_a=1e200,burden_b=1e200),"units")))
overflow$estimate <- 1e308
check("Cost-sum overflow rejected",rejects(cs_value_burden(overflow,c(burden_a=1,burden_b=1),"units")))
result <- do.call(rbind,checks)
folder <- file.path(base,"reviews/root_validation"); dir.create(folder,recursive=TRUE,showWarnings=FALSE)
write.csv(result,file.path(folder,"research_metrics_checks.csv"),row.names=FALSE)
write.csv(a$metrics,file.path(folder,"research_metrics_hand_oracle.csv"),row.names=FALSE)
write.csv(b$metrics,file.path(folder,"research_metrics_weighted_oracle.csv"),row.names=FALSE)
write.csv(boot$bootstrap,file.path(folder,"research_metrics_bootstrap_failure_audit.csv"),row.names=FALSE)
cat(nrow(result)," companion reporting checks passed.\n")
