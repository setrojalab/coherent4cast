p3_schema_fixture <- function() data.frame(id = c("PRIVATE_SUBJECT", "PRIVATE_SUBJECT", "SECOND_SUBJECT"),
  start = c(0, 1, 0), stop = c(1, 2, 2), event_type = c("a", "0", "0"), terminal = c(0, 1, 0), x = c(1, 1, 0))

test_that("trajectory alias preserves established history and schema behavior", {
  d <- p3_schema_fixture()
  z <- cs_as_trajectory(d, time_unit = "years")
  expect_identical(class(z), c("cs_trajectory", "surv_trajectory", "data.frame"))
  expect_identical(z$id, d$id)
  expect_identical(tail(names(formals(cs_as_trajectory)), 1), "terminal_cause")
  expect_identical(attr(z, "regime"), "joint_recurrent_terminal")
  expect_false(attr(z, "cs_schema")$regime_details$model_inferred)
  expect_identical(as.numeric(cs_build_history(z)$counts[, 1]), c(0, 1, 0))
  expect_match(attr(z, "cs_schema")$regime_details$scope, "do not select a likelihood")
})

test_that("regime tags do not reinterpret single observed marks as competing causes", {
  d <- data.frame(id = 1:2, start = 0, stop = 1, event_type = c("a", "b"), terminal = 0)
  z <- cs_as_trajectory(d, time_unit = "years")
  expect_identical(attr(z, "regime"), "recurrent_only")
  expect_identical(attr(z, "cs_schema")$regime_details$observed_pattern,
    "at_most_one_nonterminal_event_per_unit_observed")
  d$event_type <- "0"; d$terminal <- c(1, 0)
  expect_identical(attr(cs_as_trajectory(d, time_unit = "years"), "regime"), "standard_survival")
  d$terminal <- 0
  z <- cs_as_trajectory(d, time_unit = "years", event_types = c("a", "b"))
  expect_identical(attr(z, "regime"), "standard_survival")
  expect_identical(attr(z, "cs_schema")$regime_details$observed_pattern, "no_events_observed")
  d2 <- data.frame(id = c(1, 1), start = c(0, 1), stop = c(1, 2), event_type = "a", terminal = 0)
  z2 <- cs_as_trajectory(d2, time_unit = "years")
  expect_identical(attr(z2, "regime"), "recurrent_only")
  expect_equal(attr(z2, "cs_schema")$regime_details$maximum_observed_nonterminal_events_per_unit, 2)
})

test_that("competing cause metadata is explicit and consistent with absorption", {
  d <- data.frame(id = 1:3, start = 0, stop = 1, event_type = "0", terminal = c(1, 1, 0),
    cause = c("cause_A", "cause_B", NA))
  plain <- cs_as_trajectory(d, time_unit = "years")
  expect_identical(attr(plain, "regime"), "standard_survival")
  z <- cs_as_trajectory(d, time_unit = "years", terminal_cause = "cause")
  expect_identical(attr(z, "regime"), "competing_risks")
  expect_identical(attr(z, "cs_schema")$terminal_causes_observed, c("cause_A", "cause_B"))
  expect_identical(attr(cs_as_trajectory(z, time_unit = "years"), "cs_schema")$terminal_cause, "cause")
  d$cause[1] <- NA
  expect_error(cs_as_trajectory(d, time_unit = "years", terminal_cause = "cause"), "absorbing-event row", class = "coherentSurv_error")
  d$cause <- c("cause_A", "cause_B", "cause_C")
  expect_error(cs_as_trajectory(d, time_unit = "years", terminal_cause = "cause"), "only on an absorbing", class = "coherentSurv_error")
  expect_error(cs_as_trajectory(d, time_unit = "years", terminal_cause = c("cause", "terminal")), class = "coherentSurv_error")
  expect_error(cs_as_trajectory(d, time_unit = "years", terminal_cause = "absent"), "column is absent", class = "coherentSurv_error")
})

test_that("observation labels preserve gaps, monitoring and delayed-entry distinctions", {
  d <- p3_schema_fixture()
  z <- cs_as_trajectory(d, time_unit = "years")
