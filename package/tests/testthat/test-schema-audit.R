test_that("audit capture fingerprints data without exporting subject records", {
  d <- cs_as_trajectory(p3_schema_fixture(), time_unit = "years")
  capture <- get(".cs_capture_audit_context", envir = environment(cs_audit_report))
  ctx <- capture(d, quote(cs_fit(formula = ~x, data = data.frame(id = "PRIVATE_SUBJECT"), time_unit = "years")))
  expect_identical(ctx$data_fingerprint$algorithm, "SHA-256")
  expect_equal(nchar(ctx$data_fingerprint$value), 64)
  expect_identical(ctx$data_fingerprint$value,
    digest::digest(serialize(d, NULL, version = 3L), algo = "sha256", serialize = FALSE))
  expect_match(ctx$data_fingerprint$representation, "version = 3")
  changed <- d; changed$x[1] <- changed$x[1] + 1
  expect_false(identical(ctx$data_fingerprint$value, capture(changed)$data_fingerprint$value))
  expect_match(ctx$captured_at_utc, "Z$")
  expect_true(is.list(ctx$fit_session))
  expect_false(grepl("PRIVATE_SUBJECT", ctx$captured_call, fixed = TRUE))
  expect_match(ctx$captured_call, "audit_data_argument_redacted")
  ctx$captured_at_utc <- "2020-01-01T00:00:00.000000Z"
  fit <- structure(list(data = d, schema = attr(d, "cs_schema"), formula = ~x, n = 2L,
    npaths = 2L, targeting = "none", frailty = "gamma", convergence = list(valid = FALSE, code = "nonregular_fit"),
    audit = c(list(data_hash = "legacy_md5_value", data_hash_algorithm = "MD5 integrity fingerprint", seed = 7L), ctx)), class = "coherentSurv")
  pred <- data.frame(unit = "PRIVATE_SUBJECT", estimate = .2,
    series_error_bound = c(1e-12, 2e-12), covariate_mcse = c(0, NA_real_))
  report <- cs_audit_report(fit, predictions = pred)
  expect_identical(report$fit_context$captured_at_utc, "2020-01-01T00:00:00.000000Z")
  expect_false(identical(report$fit_context$captured_at_utc, report$export$created_at_utc))
  expect_identical(report$fit_context$legacy_fingerprint$value, "legacy_md5_value")
  expect_match(report$fit_context$legacy_fingerprint$algorithm, "MD5")
  expect_false(report$convergence$valid)
  expect_equal(report$numerical$prediction$maximum[report$numerical$prediction$metric == "series_error_bound"], 2e-12)
  expect_equal(report$numerical$prediction$nonfinite[report$numerical$prediction$metric == "covariate_mcse"], 1)
  js <- cs_audit_report(fit, predictions = pred, format = "json")
  parsed <- jsonlite::fromJSON(js)
  expect_identical(parsed$fit_context$data_fingerprint$algorithm, "SHA-256")
  expect_false(grepl("PRIVATE_SUBJECT|SECOND_SUBJECT", js))
  expect_match(paste(cs_audit_report(fit, format = "text"), collapse = "\n"), "Legacy fingerprint")
})

test_that("source hashes describe only supplied files at export", {
  a <- tempfile(); b <- tempfile(); writeBin(charToRaw("abc"), a); writeBin(charToRaw("not supplied"), b)
  on.exit(unlink(c(a, b)), add = TRUE)
  d <- cs_as_trajectory(p3_schema_fixture(), time_unit = "years")
  r <- cs_audit_report(d, source_files = c(a, a), include_session = FALSE)
  expect_equal(nrow(r$source_files), 1)
  expect_identical(r$source_files$sha256, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")
  expect_identical(r$source_files$hashed_at_utc, r$export$created_at_utc)
  expect_null(r$fit_context$captured_at_utc)
  expect_null(r$fit_context$session)
  expect_null(r$export$session)
  expect_match(r$fit_context$status, "not captured")
  expect_equal(nrow(cs_audit_report(d)$source_files), 0)
  expect_error(cs_audit_report(d, source_files = tempfile()), class = "coherentSurv_error")
  expect_error(cs_audit_report(d, source_files = tempdir()), "directories are not scanned", class = "coherentSurv_error")
  expect_error(cs_audit_report(d, source_files = NA_character_), class = "coherentSurv_error")
  changed <- d; changed$x[1] <- 99
  expect_false(identical(r$export$data_fingerprint$value, cs_audit_report(changed)$export$data_fingerprint$value))
})

test_that("audit formats write equivalent portable reports and validate their inputs", {
  d <- cs_as_trajectory(p3_schema_fixture(), time_unit = "years")
  jf <- tempfile(fileext = ".json"); tf <- tempfile(fileext = ".txt"); rf <- tempfile(fileext = ".rds")
  on.exit(unlink(c(jf, tf, rf)), add = TRUE)
  js <- cs_audit_report(d, format = "json", file = jf, include_session = FALSE)
  expect_identical(jsonlite::fromJSON(jf)$report_type, "coherentSurv_audit_report")
  expect_identical(jsonlite::fromJSON(js)$export$data_fingerprint$value, cs_audit_report(d)$export$data_fingerprint$value)
  txt <- cs_audit_report(d, format = "text", file = tf, include_session = FALSE)
  expect_identical(readLines(tf), txt)
  lst <- cs_audit_report(d, file = rf)
  expect_identical(readRDS(rf), lst)
  expect_error(cs_audit_report(list()), class = "coherentSurv_error")
  expect_error(cs_audit_report(d, include_session = NA), class = "coherentSurv_error")
  expect_error(cs_audit_report(d, file = NA_character_), class = "coherentSurv_error")
  expect_error(cs_audit_report(d, predictions = list()), class = "coherentSurv_error")
  expect_error(cs_audit_report(d, predictions = data.frame(series_error_bound = "bad")), class = "coherentSurv_error")
  p <- data.frame(estimate = .5); class(p) <- c("coherentSurv_prediction", "data.frame")
  expect_equal(nrow(cs_audit_report(p)$numerical$prediction), 0)
  expect_null(cs_audit_report(p)$export$data_fingerprint)
})

