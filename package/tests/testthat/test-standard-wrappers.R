wrapper_data <- function() data.frame(id=1:12,time=c(.2,.3,.4,.5,.6,.8,1,1.2,1.3,1.5,1.7,2),
  status=c(1,2,0,1,0,2,1,0,2,0,1,0),x=rep(0:1,6))

test_that("survival wrapper is the unchanged zero-frailty likelihood", {
  d<-wrapper_data();d$status<-as.integer(d$status>0)
  s<-rc_surv(~1,d,unit="id",time_unit="year",frailty_diagnostics=FALSE)
  expected<-sum(d$status)/sum(d$time)
  expect_s3_class(s,"coherent4cast_surv");expect_s3_class(s,"coherent4cast")
  expect_equal(s$phi,0);expect_identical(s$frailty_requested,"none")
  expect_equal(unname(exp(coef(s))),expected,tolerance=1e-7)
  raw<-transform(d,start=0,event_type="none",terminal=status,stop=time)
  old<-coherent4cast(~1,raw,time_unit="year",control=coherent4cast_control(phi_fixed=0),frailty_diagnostics=FALSE)
  expect_equal(coef(s),coef(old),tolerance=1e-12)
  expect_equal(vcov(s),vcov(old),tolerance=1e-12)
  expect_equal(as.numeric(logLik(s)),as.numeric(logLik(old)),tolerance=1e-12)
  p<-predict(s,landmark=0,horizon=c(.4,1),type="all")
  expect_s3_class(p,"rc_forecast")
  expect_equal(p$estimate[p$target=="risk"],1-exp(-expected*p$horizon[p$target=="risk"]),tolerance=1e-7)
  expect_equal(p$estimate[p$target=="rmst"],(1-exp(-expected*p$horizon[p$target=="rmst"]))/expected,tolerance=1e-7)
  two<-rc_surv(survival::Surv(time,status)~1,d,unit="id",time_unit="year",frailty_diagnostics=FALSE)
  expect_equal(coef(s),coef(two),tolerance=1e-12)
  prof<-predict(s,newdata=data.frame(id=101),landmark=.5,horizon=1,type="risk")
  expect_equal(prof$estimate,1-exp(-expected),tolerance=1e-7)
  expect_match(attr(prof,"profile_assumption"),"declared eligible")
  expect_error(rc_surv(~status,d,time_unit="year"),"cannot be predictors")
  expect_error(coherent4cast(~1,raw,time_unit="year",frailty="none",control=coherent4cast_control(phi_fixed=1)),"conflicts")
})

test_that("competing CIFs use every cause and preserve probability mass", {
  d<-wrapper_data();fit<-rc_competing(~1,d,unit="id",time_unit="year",frailty_diagnostics=FALSE)
  rates<-as.numeric(table(factor(d$status,levels=c(1,2))))/sum(d$time);total<-sum(rates)
  expect_s3_class(fit,"coherent4cast_competing")
  expect_equal(unname(exp(coef(fit))),rates,tolerance=1e-7)
  p<-predict(fit,newdata=data.frame(id=100),landmark=.5,horizon=c(.5,1),type="all")
  expect_s3_class(p,"rc_forecast")
  for(h in c(.5,1)){
    row<-p[p$horizon==h,];actual<-stats::setNames(row$estimate,row$target)
    expect_equal(unname(actual[c("cif_1","cif_2")]),rates/total*(1-exp(-total*h)),tolerance=1e-7)
    expect_equal(unname(actual["survival"]+sum(actual[c("cif_1","cif_2")])),1,tolerance=1e-12)
    expect_equal(unname(actual["risk"]),sum(actual[c("cif_1","cif_2")]),tolerance=1e-12)
    expect_equal(unname(actual["rmst"]),(1-exp(-total*h))/total,tolerance=1e-7)
    expect_true(all(actual[c("cif_1","cif_2")] < 1-exp(-rates*h)))
  }
  H<-diag(as.numeric(table(factor(d$status,levels=c(1,2)))))
  scores<-cbind(as.integer(d$status==1)-rates[1]*d$time,as.integer(d$status==2)-rates[2]*d$time)
  oracleV<-solve(H)%*%crossprod(scores)%*%solve(H)
  expect_equal(unname(vcov(fit)),oracleV,tolerance=1e-7)
  expect_equal(as.numeric(logLik(fit)),sum(vapply(fit$fits,function(f)as.numeric(logLik(f)),numeric(1))),tolerance=1e-12)
  observed<-predict(fit,landmark=.7,horizon=1)
  expect_false(any(observed$unit%in%c("1","2","4")))
  expect_error(rc_competing(~1,d,time_unit="year",causes=c("1","2","3")),"No events support")
  expect_error(rc_competing(~status,d,time_unit="year"),"cannot be predictors")
  expect_error(predict(fit,newdata=data.frame(id=1),horizon=1,covariate_evolution="joint_submodel"),"arg")
})

test_that("ordered competing hazards agree with a separate two-step calculation", {
  d<-wrapper_data();f<-rc_competing(~1,d,unit="id",time_unit="year",breaks=c(0,.7,Inf),frailty_diagnostics=FALSE)
  h<-1.2;p<-predict(f,newdata=data.frame(id=101),horizon=h,type="all")
  exposure<-c(sum(pmin(d$time,.7)),sum(pmax(d$time-.7,0)))
  rate<-sapply(c(1,2),function(k)c(sum(d$status==k&d$time<=.7),sum(d$status==k&d$time>.7))/exposure)
  s<-1;cif<-c(0,0);m<-0
  for(j in 1:2){dt<-c(.7,.5)[j];q<-sum(rate[j,]);a<-(1-exp(-q*dt))/q;cif<-cif+s*rate[j,]*a;m<-m+s*a;s<-s*exp(-q*dt)}
  expected<-c(cif,s,1-s,m)
  expect_equal(p$estimate,expected,tolerance=1e-6)
})

test_that("competing validation observes competing events as noncases", {
  d<-wrapper_data();f<-rc_competing(~1,d,time_unit="year",frailty_diagnostics=FALSE)
  v<-validate(f,time=c(.2,.3,2,2),status=c(1,2,0,0),horizon=1,cause="1",predicted=c(.8,.7,.2,.1),threshold=.5)
  expect_equal(unname(v$confusion),matrix(c(1,1,0,2),2,2))
  expect_equal(v$metrics$estimate[v$metrics$metric=="Brier"],(.04+.49+.04+.01)/4,tolerance=1e-12)
  expect_equal(v$metrics$estimate[v$metrics$metric=="AUROC"],1)
  expect_equal(v$controls,3);expect_equal(v$competing_events_by_horizon,1)
  expect_match(v$assumptions,"competing events are observed noncases",ignore.case=TRUE)
  g<-list(event=c(.5,.25,1,1),horizon=rep(.5,4))
  w<-validate(f,time=c(.2,.3,2,2),status=c(1,2,0,0),horizon=1,cause="1",predicted=c(.8,.7,.2,.1),threshold=.5,censor_survival=g)
  expect_equal(w$weights,c(2,4,2,2))
  expect_equal(w$metrics$estimate[w$metrics$metric=="Brier"],(2*.04+4*.49+2*.04+2*.01)/4,tolerance=1e-12)
  expect_error(validate(f,time=c(.2,.3),status=c(1,2),horizon=1,cause="1",predicted=c(.8,.7),censor_survival=list(event=c(.5,0),horizon=c(.5,.5))),"positive")
  expect_error(validate(f,time=c(.2,.3),status=c(0,0),horizon=1,cause="1",predicted=c(.8,.7)),"No observed cases")
})

test_that("new wrappers retain observation and cause coding guards", {
  d<-wrapper_data();d$entry<-.1
  expect_error(rc_competing(~1,d,start="entry",unit="id",time_unit="year"),"origin")
  d$status<-factor(ifelse(d$status==0,"censored",paste0("cause",d$status)))
  expect_error(rc_competing(~1,d,time_unit="year"),"censor_code")
  f<-rc_competing(~1,d,time_unit="year",censor_code="censored",frailty_diagnostics=FALSE)
  expect_identical(f$causes,c("cause1","cause2"))
  expect_error(rc_surv(~1,d,time_unit="year"),"0=censored")
})
