p6_wrapper_data <- function() data.frame(id=1:12,
  time=c(.2,.3,.4,.5,.6,.8,1,1.2,1.3,1.5,1.7,2),
  status=c(1,2,0,1,0,2,1,0,2,0,1,0),x=rep(0:1,6))

test_that("survival schema errors cannot silently remap outcomes", {
  d <- p6_wrapper_data(); d$status <- as.integer(d$status>0)
  expect_error(rc_surv("x",d,time_unit="years"),"Supply a formula")
  expect_error(rc_surv(y~x,d,time_unit="years"),"Surv")
  expect_error(rc_surv(~x,d[FALSE,],time_unit="years"),"nonempty")
  reserved <- d; reserved$.rcw_unit <- reserved$id
  expect_error(rc_surv(~x,reserved,time_unit="years"),"reserved")
  expect_error(rc_surv(~missing_predictor,d,time_unit="years"),"predictor column")
  expect_error(rc_surv(~x,d[,setdiff(names(d),"time")],time_unit="years"),"both follow-up")
  expect_error(rc_surv(~x,d,unit="missing",time_unit="years"),"unit column")
  expect_error(rc_surv(~x,d,start="entry",time_unit="years"),"explicit unit")
  expect_error(rc_surv(~x,d,start="entry",unit="id",time_unit="years"),"start column")
  missing_status <- d; missing_status$status[1] <- NA
  expect_error(rc_surv(~x,missing_status,time_unit="years"),"cannot be missing")
  expect_error(do.call(rc_surv,c(list(formula=~x,data=d,time="time",status="status",
    unit=NULL,start=NULL,time_unit="years",breaks=c(0,Inf),control=recurcast_control()),list(1))),"must be named")
  expect_error(rc_surv(~x,d,time_unit="years",observation="coarsened"),"fixed by these wrappers")
  fit <- rc_surv(~x,d,unit="id",time_unit="years",frailty_diagnostics=FALSE)
  expect_error(predict(fit,data.frame(id=c(99,99),x=0),horizon=1),"one covariate-only profile")
  expect_error(predict(fit,data.frame(id=99,x=0),horizon=1,newdata_future=1),"data frame of future")
  expect_error(predict(fit,data.frame(id=99,x=0),horizon=1,newdata_future=data.frame(time=.2,x=1)),"unit column")
})

test_that("future wrapper updates retain the declared identifier and prediction law", {
  d <- p6_wrapper_data(); b <- transform(d,status=as.integer(status>0))
  fit <- rc_surv(~x,b,unit="id",time_unit="years",frailty_diagnostics=FALSE)
  profile <- data.frame(id=99,x=0)
  update <- data.frame(id=99,time=.5,x=1)
  out <- predict(fit,profile,horizon=1,type="risk",covariate_evolution="locf",newdata_future=update)
  rate0 <- exp(coef(fit)[1]); rate1 <- exp(sum(coef(fit)))
  expect_equal(out$estimate,unname(1-exp(-.5*(rate0+rate1))),tolerance=1e-7)
  cf <- rc_competing(~x,d,unit="id",time_unit="years",frailty_diagnostics=FALSE)
  pred <- predict(cf,profile,horizon=1,type="all",covariate_evolution="locf",newdata_future=update)
  rate <- sapply(cf$fits,function(f)exp(c(coef(f)[1],sum(coef(f)))))
  s <- 1; cif <- c(0,0)
  for(j in 1:2){q <- sum(rate[j,]);cif <- cif+s*rate[j,]*(-expm1(-q*.5))/q;s<-s*exp(-q*.5)}
  expect_equal(pred$estimate[1:2],unname(cif),tolerance=1e-7)
  expect_equal(pred$estimate[pred$target=="survival"],s,tolerance=1e-7)
  expect_output(print(cf),"competing-risk")
  expect_equal(tidy(cf)$estimate,unname(coef(cf)))
  expect_match(summary(cf)$interval_scope,"no automatic CIF confidence")
  expect_equal(glance(cf)$AIC,-2*as.numeric(logLik(cf))+2*length(coef(cf)))
})

test_that("competing schema and eligibility guards reject unsupported experiments", {
  d <- p6_wrapper_data()
  expect_error(rc_competing(~x,d,censor_code=NA,time_unit="years"),"censoring code")
  expect_error(rc_competing(~x,d[,setdiff(names(d),"status")],time_unit="years"),"status/cause")
  expect_error(rc_competing(~x,d,causes=c(1,1),time_unit="years"),"distinct")
  expect_error(rc_competing(~x,d,causes=1,time_unit="years"),"outside the declared")
  fit <- rc_competing(~1,d,unit="id",time_unit="years",frailty_diagnostics=FALSE)
  expect_error(predict(fit,horizon=1,unknown=TRUE),"Unsupported")
  expect_error(predict(fit,horizon=0),"positive finite")
  expect_error(predict(fit,landmark=NA,horizon=1),"nonnegative")
  split <- data.frame(id=c(1,1,2,3),entry=c(0,.6,0,0),time=c(.4,1,1,1),status=c(0,1,2,0))
  expect_error(rc_competing(~1,split,start="entry",unit="id",time_unit="years"),"contiguous")
  train <- transform(d,entry=0)
  fs <- rc_competing(~1,train,start="entry",unit="id",time_unit="years",frailty_diagnostics=FALSE)
  late <- data.frame(id=99,entry=.1,time=2,status=0)
  expect_error(predict(fs,late,horizon=1),"contiguous eligible")
})

test_that("competing validation rejects invalid weights and preserves stratified endpoints", {
  f <- rc_competing(~1,p6_wrapper_data(),time_unit="years",frailty_diagnostics=FALSE)
  t <- c(.2,.4,2,2); s <- c(1,2,0,0); p <- c(.8,.7,.2,.1)
  expect_error(validate(f,t,s,1,"unknown",p),"Select one")
  expect_error(validate(f,t,s,1,"1",p,unused=TRUE),"Unsupported")
  expect_error(validate(f,-t,s,1,"1",p),"nonnegative")
  expect_error(validate(f,t,s,Inf,"1",p),"finite positive")
  expect_error(validate(f,t,s,1,"1",p,censor_survival=list(event=1,horizon=1)),"length n")
  expect_error(validate(f,t,s,1,"1",p,censor_survival=list(event=rep(1.1,4),horizon=rep(1,4))),"lie in")
  expect_error(validate(f,t,s,1,"1",p,censor_survival=list(event=rep(Inf,4),horizon=rep(1,4))),"lie in")
  strat <- validate(f,t,s,1,"1",p,strata=c("a","a","b","b"))
  expect_match(strat$a$endpoint,"observed noncases")
  expect_identical(strat$b$cause,"1")
  expect_equal(strat$a$controls,1)
})
