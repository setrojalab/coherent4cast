args <- commandArgs(trailingOnly = TRUE)
path <- if (length(args)) normalizePath(args[[1]]) else normalizePath(".")
public <- c("rc_causal", "rc_causal_contrast", "rc_surv","rc_competing","rc_audit_report","rc_coarsen_fibre","rc_fibre_mcse","rc_colon_fibre","rc_predict_coarsened","rc_generator_csr","rc_propagate_sparse","rc_bounds_sparse","rc_frailty_loglik","rc_frailty_diagnose","rc_covariate_model", "as_trajectory", "build_history", "recurcast_control", "recurcast",
            "rc_loglik", "rc_coarsen", "rc_propagate", "rc_target", "rc_bounds",
            "rc_conformal", "rc_pivot", "rc_cornish_fisher", "rc_identify",
            "rc_band", "rc_filter_paths", "bounds", "conformal", "validate", "tidy", "glance",
            "augment", "autoplot", "simulate_recurcast", "rc_simulate", "rc_predict_paths", "rc_readmission", "rc_colon", "rc_regularize")
defs <- unlist(lapply(list.files(file.path(path, "R"), full.names = TRUE), function(f) {
  x <- parse(f)
  vapply(x, function(e) {
    if (is.call(e) && identical(e[[1]], as.name("<-")) && is.symbol(e[[2]]) &&
        is.call(e[[3]]) && identical(e[[3]][[1]], as.name("function")))
      as.character(e[[2]]) else ""
  }, character(1))
}))
exports <- intersect(public, defs)
methods <- defs[grepl("^(print|summary|predict|plot|coef|vcov|logLik|nobs|tidy|glance|augment|autoplot|bounds|conformal|validate)\\.", defs)]
registration <- vapply(methods, function(m) {
  split <- regexpr("\\.", m)
  paste0("S3method(", substr(m, 1, split - 1), ",", substr(m, split + 1, nchar(m)), ")")
}, character(1))
writeLines(c("# Generated by tools/update-namespace.R from the explicit public API.",
             "useDynLib(recurcast, .registration = TRUE)", "importFrom(Rcpp, evalCpp)",
             "importFrom(stats, predict)", "importFrom(utils, head, tail, capture.output)",
             paste0("export(", exports, ")"), registration), file.path(path, "NAMESPACE"))
cat("Registered", length(exports), "exports and", length(registration), "S3 methods.\n")

