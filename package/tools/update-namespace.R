args <- commandArgs(trailingOnly = TRUE)
path <- if (length(args)) normalizePath(args[[1]]) else normalizePath(".")
public <- c("cs_validate_env", "cs_from_adam", "cs_from_omop", "cs_causal", "cs_causal_contrast", "cs_surv","cs_competing","cs_audit_report","cs_coarsen_fibre","cs_fibre_mcse","cs_colon_fibre","cs_predict_coarsened","cs_generator_csr","cs_propagate_sparse","cs_bounds_sparse","cs_frailty_loglik","cs_frailty_diagnose","cs_covariate_model", "cs_as_trajectory", "cs_build_history", "cs_control", "cs_fit",
            "cs_loglik", "cs_coarsen", "cs_propagate", "cs_target", "cs_bounds",
            "cs_conformal", "cs_pivot", "cs_cornish_fisher", "cs_identify",
            "cs_band", "cs_filter_paths", "bounds", "conformal", "validate", "tidy", "glance",
            "augment", "autoplot", "cs_simulate", "cs_predict_paths", "cs_readmission", "cs_colon", "cs_regularize")
defs <- unlist(lapply(list.files(file.path(path, "R"), full.names = TRUE), function(f) {
  x <- parse(f)
  vapply(x, function(e) {
    if (is.call(e) && identical(e[[1]], as.name("<-")) && is.symbol(e[[2]]) &&
        is.call(e[[3]]) && identical(e[[3]][[1]], as.name("function")))
      as.character(e[[2]]) else ""
  }, character(1))
}))
exports <- intersect(public, defs)
methods <- defs[grepl("^(print|summary|predict|plot|coef|vcov|confint|logLik|nobs|tidy|glance|augment|autoplot|bounds|conformal|validate)\\.", defs)]
registration <- vapply(methods, function(m) {
  split <- regexpr("\\.", m)
  paste0("S3method(", substr(m, 1, split - 1), ",", substr(m, split + 1, nchar(m)), ")")
}, character(1))
writeLines(c("# Generated by tools/update-namespace.R from the explicit public API.",
             "useDynLib(coherentSurv, .registration = TRUE)", "importFrom(Rcpp, evalCpp)",
             "importFrom(stats, predict, confint)", "importFrom(utils, head, tail, capture.output)",
             paste0("export(", exports, ")"), registration), file.path(path, "NAMESPACE"))
cat("Registered", length(exports), "exports and", length(registration), "S3 methods.\n")

